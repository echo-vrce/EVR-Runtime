// AtlasCDN client (PC): signed per-guild index -> verified, cached files -> served through the resource hook.
//
// Base URL: plugins\config.json "cdn_base" when set (dev: a local http.server over `evr-sign cdn` output), else the
// game's apiservice_host (Atlas). The index is fetched with the player's runtime token, from which Atlas picks the
// player's active guild. Every file is checked by size and sha256 before it is cached or served, and the index by an
// Ed25519 signature from a key pinned at build time (keys/cdn_pinned.txt). A lower serial than the last one accepted
// for the same guild is refused, so an older set can't be replayed.
